import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const target = path.join(packageRoot, 'src', 'lib', 'telemetry-config.ts');
const projectKey = process.env.LIM_POSTHOG_PROJECT_KEY ?? '';
const host = process.env.LIM_POSTHOG_HOST ?? 'https://us.i.posthog.com';
const tsString = (value) => `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;

fs.writeFileSync(
  target,
  `// Generated by scripts/generate-telemetry-config.mjs during release builds.
// Empty values keep local and unconfigured builds fail-open/no-op.
export const DEFAULT_POSTHOG_PROJECT_KEY = ${tsString(projectKey)};
export const DEFAULT_POSTHOG_HOST = ${tsString(host)};
`,
);
