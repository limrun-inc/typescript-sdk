#!/usr/bin/env node
// Regenerates the base64 GLB modules in src/assets/models/.
//
// The 3D simulator view renders photoreal device models (see
// src/components/device-3d/realistic-model.ts). The GLB binaries are
// committed as generated `.b64.ts` modules — base64 data URIs behind a
// dynamic import — so that:
//   - vite lib mode doesn't inline them into the main bundle (consumers only
//     download the ~1MB model chunk when the 3D view is actually used), and
//   - no binary assets or runtime CDN fetches are needed.
//
// Sources (both CC BY 4.0, attribution in CREDITS.md and embedded in each
// file's glTF `asset.extras`):
//   - "Apple iPhone 15 Pro Max Black" by polyman
//     https://sketchfab.com/3d-models/apple-iphone-15-pro-max-black-df17520841214c1792fb8a44c6783ee7
//   - "Apple watch series 5" by atomle
//     https://sketchfab.com/3d-models/apple-watch-series-5-16950208bdf041f193c31d3b4a0ac15a
//
// To regenerate from the original Sketchfab exports, optimize first:
//   npx gltf-transform optimize in.glb out.glb \
//     --compress meshopt --texture-compress webp --texture-size 1024
// then drop the optimized .glb files next to this script's targets and run:
//   node scripts/encode-model-assets.mjs path/to/iphone.glb path/to/watch.glb

import { readFileSync, writeFileSync } from 'fs';
import { basename, join, dirname } from 'path';
import { fileURLToPath } from 'url';

const outDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'assets', 'models');

const files = process.argv.slice(2);
if (files.length === 0) {
  console.error('usage: node scripts/encode-model-assets.mjs <model.glb> [...]');
  process.exit(1);
}

for (const file of files) {
  const data = readFileSync(file);
  const name = basename(file, '.glb');
  const out = join(outDir, `${name}.glb.b64.ts`);
  const contents =
    `// AUTOGENERATED by scripts/encode-model-assets.mjs from ${basename(file)} — do not edit.\n` +
    `// Third-party CC BY 4.0 model; author/license/source are embedded in the\n` +
    `// glTF asset.extras and listed in packages/ui/CREDITS.md.\n` +
    `export default\n  'data:model/gltf-binary;base64,${data.toString('base64')}';\n`;
  writeFileSync(out, contents);
  console.log(`${out} (${(contents.length / 1024 / 1024).toFixed(2)} MB)`);
}
